// =============================================================================
// 出力ガード — LLMが答えてしまった危険な断定を、送信前に止める
// =============================================================================
//
// 【なぜ必要か】
// ガードレールはシステムプロンプトに書いてあるだけで、**強制力がない**。
// LLMが破ったらそのまま送信される。実際にこのリポジトリには
// knowledge-packs/yukkuri-exosome（エクソソーム＝承認医薬品が存在しない領域）が
// 本番登録されており、最も規制の厳しい領域が最も軟らかい防御で動いていた。
//
// SaMD該当性ガイドライン脚注12は「『医療機器ではない』旨の記載があっても、
// 医療機器ではないことの根拠とはならない」と明記している。
// **免責文は必要条件であって十分条件ではない**。実際の出力を止める層が要る。
//
// 【設計方針: 誤検知を出さない】
// 過剰に止めると運用者が無効化する。無効化されたガードは無いのと同じ。
// そこで**断定の言い回しだけ**を対象にする:
//   ×「治ります」「効果があります」 → 止める
//   ○「〜という報告があります」「医師にご相談ください」 → 通す
//
// 【止め方: 無言にしない】
// 検出しても黙って落とさない。安全な定型文に**差し替える**。
// このリポジトリ全体の「無応答ゼロ化」の原則と揃える。

/** 危険と判定した理由。ログと管理画面で使う。 */
export type GuardCategory = 'medical' | 'legal' | 'financial';

export interface GuardRule {
  category: GuardCategory;
  /** 何を検出するか（人が読む用）。 */
  label: string;
  /** 断定表現のパターン。 */
  pattern: RegExp;
}

/**
 * 検出ルール。
 *
 * 【足すときの約束】
 * 「その言い回しが出たら実際に法令違反になりうるか」で判断する。
 * 不安だから広く止める、をやると誤検知が増えて無効化される。
 */
export const GUARD_RULES: GuardRule[] = [
  // ── 医療（薬機法・医師法） ────────────────────────────────────────────
  {
    category: 'medical',
    label: '効果・治癒の断定',
    // 「〜が治ります」「〜に効きます」「効果があります」等。
    // 「〜という報告がある」「〜と言われている」は伝聞なので対象外。
    // 疑問形（「効果がありますか」）は断定ではないので、各分岐の末尾で除外する。
    pattern:
      /治りま(す(?!か)|した)|完治しま(す(?!か)|した)|治せます(?!か)|効果があ(ります(?!か)|る(?!の?か))|効果が出ま(す(?!か)|した)|効きま(す(?!か)|した)/,
  },
  {
    category: 'medical',
    label: '診断・病名の断定',
    // 「〜の可能性が高いです」「〜だと思われます（病名）」など個別の判断。
    // 医師法17条は「個人を特定して病名＋罹患可能性」を示すことを問題にする。
    pattern: /(それは|おそらく|恐らく).{0,12}(症|病|炎|がん|癌|うつ|障害)(です|でしょう|だと思います)/,
  },
  {
    category: 'medical',
    label: '受診不要の示唆',
    // 「病院に行かなくても大丈夫」は最も危険。受診機会を奪う。
    pattern: /(病院|医者|医師|受診).{0,8}(行かなくて|行く必要は|不要)/,
  },
  {
    category: 'medical',
    label: '薬の用法・中止の指示',
    pattern: /(薬|処方|服用).{0,10}(やめて|中止して|飲まないで|減らして)(ください|ね|)/,
  },

  // ── 法律（弁護士法72条） ──────────────────────────────────────────────
  {
    category: 'legal',
    label: '個別の法的判断',
    // 「これは違法です」「勝てます」等の断定。一般的な制度説明は対象外。
    pattern: /(違法|合法|無効|有効)(です|でしょう)|(訴訟|裁判).{0,8}(勝て|勝ち)(ます|る)/,
  },

  // ── 金融（金商法・保険業法） ──────────────────────────────────────────
  {
    category: 'financial',
    label: '投資の勧誘・断定',
    pattern: /(儲かり(ます|ました)|値上がりし(ます|)|上がり(ます|)よ|絶対に?(儲|得))/,
  },
];

export interface GuardResult {
  /** 危険と判定したか。 */
  blocked: boolean;
  /** 送信してよいテキスト（blockedなら差し替え後）。 */
  text: string;
  /** 何に引っかかったか。ログ用。 */
  hits: Array<{ category: GuardCategory; label: string }>;
}

/** 差し替え後の文面。領域ごとに、次の行動を示して終える。 */
const REPLACEMENT: Record<GuardCategory, string> = {
  medical:
    'ごめんね、その内容はわたしからお答えするのが難しいところなの。' +
    '体のことは、お医者さんに直接みてもらうのがいちばん確実だよ。',
  legal:
    'ごめんね、法律にかかわる判断はわたしからはお答えできないの。' +
    '弁護士さんなど専門の方に相談してみてね。',
  financial:
    'ごめんね、お金の運用にかかわる判断はわたしからはお答えできないの。' +
    '専門の窓口に相談してみてね。',
};

/**
 * 生成されたテキストを検査し、危険なら安全な文面に差し替える。
 *
 * @param text LLMが生成したテキスト
 * @param enabled 無効化したい場合はfalse（既定は有効）
 */
export function guardOutput(text: string, enabled = true): GuardResult {
  if (!enabled || !text) return { blocked: false, text, hits: [] };

  const hits = GUARD_RULES.filter((r) => r.pattern.test(text)).map((r) => ({
    category: r.category,
    label: r.label,
  }));

  if (hits.length === 0) return { blocked: false, text, hits: [] };

  // 複数該当した場合は最初のカテゴリの文面を使う（医療 > 法律 > 金融 の順に並べてある）
  return { blocked: true, text: REPLACEMENT[hits[0].category], hits };
}
