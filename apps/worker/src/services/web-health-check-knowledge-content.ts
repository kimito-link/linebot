export function buildSystemPrompt(kbContext: string): string {
  const parts = [PERSONA_MD, GUARDRAILS_MD];
  if (kbContext.trim()) {
    parts.push(`# 参考ナレッジ（回答の根拠として使う）\n\n${kbContext}`);
  }
  parts.push(
    '上記を守りつつ、ユーザーの質問に答えてください。担当者確認が必要な場合は応答末尾に [ESCALATE] を付けてください。',
  );
  return parts.join('\n\n');
}

/** Tier0.5: LLM不要の定型応答（canonical → キャッシュ対象） */
export function matchCannedResponse(text: string): string | null {
  const normalized = text.trim().replace(/\s+/g, '');
  // 結果の読み方。「見方」より先に判定しないと services 側に吸われるため順序に注意。
  if (/結果.*見方|見方.*結果|健全|要対応|検出.*ゼロ|何も出な|結果.*意味/i.test(normalized)) {
    return CANNED_RESULT_GUIDE;
  }
  if (/何.*頼め|頼めるの|できること|依頼.*内容|サービス.*一覧|料金|いくら|費用/i.test(normalized)) {
    return CANNED_SERVICES_OVERVIEW;
  }
  if (/^(はじめまして|こんにちは|よろしく|使い方.*教え|はじめ方|始め方)/i.test(normalized)) {
    return CANNED_GREETING;
  }
  return null;
}

